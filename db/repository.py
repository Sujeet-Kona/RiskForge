"""Writing and reading audit records.

Two operations, one table. There is no query builder, no filter DSL and no
generic base class: the audit store has exactly one job, which is to hold a
decision that has already been made. Nothing here scores a transaction, derives a
probability, applies a threshold or knows what a model is.

``AuditRecord`` is the boundary type. It is a plain dataclass so that the serving
layer can describe what to persist without importing SQLAlchemy, and so that a
record read back can be compared field-for-field with the record written.
"""

from __future__ import annotations

import logging
import math
import numbers
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, fields
from datetime import datetime
from typing import Any, Protocol

from sqlalchemy.exc import SQLAlchemyError

from db.models import DECISION_VALUES, RiskDecision
from db.session import AuditDatabase


logger = logging.getLogger("riskforge.audit")


class AuditPersistenceError(RuntimeError):
    """A decision could not be written to, or read from, the audit store.

    Carries no SQL, no connection string and no driver detail. The cause is
    logged server-side, and the caller turns this into a sanitized response.
    """


@dataclass(frozen=True)
class AuditRecord:
    """One decision, in the terms the API reported it.

    Validated here as well as by the database's own constraints, because the
    audit store is the last thing to see a decision before it is stored: a
    probability outside [0, 1] or a decision outside the policy vocabulary is a
    bug in the service, and rejecting it in Python names the field instead of
    surfacing as a constraint violation from a driver.

    ``id`` and ``created_at`` are generated by the database. They are ``None`` on
    the way in and always populated on the way out.
    """

    transaction_id: str
    risk_probability: float
    decision: str
    reason_codes: list[dict[str, Any]]
    risk_decreasing_signals: list[dict[str, Any]]
    decision_reason_code: dict[str, Any]
    decision_explanation: str
    model_detail: dict[str, Any]
    policy_detail: dict[str, Any]
    scored_inputs: dict[str, Any]
    top_k: int
    model_version: str
    feature_version: str
    policy_version: str
    feature_count: int
    history_transactions_used: int

    id: int | None = None
    created_at: datetime | None = None

    def __post_init__(self) -> None:
        _require_text(self.transaction_id, "transaction_id")
        _require_probability(self.risk_probability)

        if self.decision not in DECISION_VALUES:
            raise ValueError(
                f"decision must be one of {sorted(DECISION_VALUES)}, "
                f"got {self.decision!r}."
            )

        for name in ("reason_codes", "risk_decreasing_signals"):
            entries = getattr(self, name)

            if isinstance(entries, (str, bytes)) or not isinstance(entries, Sequence):
                raise TypeError(f"{name} must be a sequence of mappings.")

            for position, entry in enumerate(entries):
                if not isinstance(entry, Mapping):
                    raise TypeError(f"{name}[{position}] must be a mapping.")

        for name in (
            "decision_reason_code",
            "model_detail",
            "policy_detail",
            "scored_inputs",
        ):
            if not isinstance(getattr(self, name), Mapping):
                raise TypeError(f"{name} must be a mapping.")

        _require_text(self.decision_explanation, "decision_explanation")

        for name in ("model_version", "feature_version", "policy_version"):
            _require_text(getattr(self, name), name)

        _require_count(self.top_k, "top_k", minimum=1)
        _require_count(self.feature_count, "feature_count", minimum=1)
        _require_count(
            self.history_transactions_used, "history_transactions_used", minimum=0
        )


# The decision fields, which map one-to-one onto columns. Derived from the
# dataclass so a new field cannot be added to the record and silently dropped on
# the way to the database.
AUDIT_RECORD_FIELDS: tuple[str, ...] = tuple(
    field.name
    for field in fields(AuditRecord)
    if field.name not in {"id", "created_at"}
)


class AuditStore(Protocol):
    """What the serving layer needs from the audit store.

    Declared so a test can supply an in-memory double without inheriting from the
    PostgreSQL implementation, and so the dependency is on three operations rather
    than on a driver.
    """

    def create_audit_record(self, record: AuditRecord) -> int: ...

    def get_audit_record(self, decision_id: int) -> AuditRecord | None: ...

    def is_ready(self) -> bool: ...


@dataclass(frozen=True)
class AuditRepository:
    """The PostgreSQL audit store. Holds a session per operation, never between."""

    database: AuditDatabase

    def create_audit_record(self, record: AuditRecord) -> int:
        """Persist one decision and return its audit identifier."""
        try:
            with self.database.session_factory() as session:
                row = RiskDecision(
                    **{name: getattr(record, name) for name in AUDIT_RECORD_FIELDS}
                )
                session.add(row)
                session.commit()

                return int(row.id)
        except SQLAlchemyError as error:
            logger.error(
                "could not persist the audit record for transaction %s",
                record.transaction_id,
                exc_info=error,
            )
            raise AuditPersistenceError(
                "The risk decision could not be written to the audit store."
            ) from error

    def get_audit_record(self, decision_id: int) -> AuditRecord | None:
        """Read one decision back, or ``None`` if it was never recorded."""
        try:
            with self.database.session_factory() as session:
                row = session.get(RiskDecision, decision_id)

                return None if row is None else _to_record(row)
        except SQLAlchemyError as error:
            logger.error("could not read audit record %s", decision_id, exc_info=error)
            raise AuditPersistenceError(
                "The audit record could not be read from the audit store."
            ) from error

    def is_ready(self) -> bool:
        return self.database.is_ready()


def _to_record(row: RiskDecision) -> AuditRecord:
    return AuditRecord(
        **{name: getattr(row, name) for name in AUDIT_RECORD_FIELDS},
        id=int(row.id),
        created_at=row.created_at,
    )


def _require_text(value: Any, name: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be a non-blank string.")


def _require_probability(value: Any) -> None:
    if isinstance(value, bool) or not isinstance(value, numbers.Real):
        raise TypeError("risk_probability must be a real number.")

    if not math.isfinite(float(value)) or not 0.0 <= float(value) <= 1.0:
        raise ValueError("risk_probability must be a finite number between 0 and 1.")


def _require_count(value: Any, name: str, *, minimum: int) -> None:
    if isinstance(value, bool) or not isinstance(value, numbers.Integral):
        raise TypeError(f"{name} must be an integer.")

    if int(value) < minimum:
        raise ValueError(f"{name} must be at least {minimum}.")
